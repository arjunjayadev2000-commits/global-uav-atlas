#!/usr/bin/env python3
"""Generate the HTV research test worlds (SDF 1.9, Gazebo Harmonic).

Deterministic: re-running reproduces identical files. Worlds are civilian
test-ground layouts (test track, obstacle course, rough ground, slopes, a
GNSS-degraded built-up corridor). Nothing here models a battlefield.

    python3 generate_worlds.py [output_dir]
"""

from __future__ import annotations

import math
import random
import sys
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parents[1] / "worlds"

GREY = "0.55 0.55 0.55 1"
CONCRETE = "0.70 0.70 0.68 1"
ROCK = "0.42 0.38 0.33 1"
DIRT = "0.50 0.42 0.30 1"
ORANGE = "0.95 0.45 0.05 1"
WHITE = "0.95 0.95 0.95 1"


def header(name: str, lat: float = 47.0, lon: float = 8.0) -> str:
    return f"""<?xml version="1.0" ?>
<!-- Generated by htv_gazebo/scripts/generate_worlds.py - do not edit by hand. -->
<sdf version="1.9">
  <world name="{name}">
    <physics name="2ms" type="ignored">
      <max_step_size>0.002</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-navsat-system" name="gz::sim::systems::NavSat"/>
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{lat}</latitude_deg>
      <longitude_deg>{lon}</longitude_deg>
      <elevation>400</elevation>
      <heading_deg>0</heading_deg>
    </spherical_coordinates>
    <scene>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.7 0.8 0.9 1</background>
      <shadows>true</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 50 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.2 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>600 600</size></plane></geometry>
          <surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>600 600</size></plane></geometry>
          <material><ambient>0.45 0.50 0.38 1</ambient><diffuse>0.45 0.50 0.38 1</diffuse></material>
        </visual>
      </link>
    </model>
"""


FOOTER = "  </world>\n</sdf>\n"


def _material(color: str) -> str:
    return f"<material><ambient>{color}</ambient><diffuse>{color}</diffuse></material>"


def box(name: str, pose: tuple[float, ...], size: tuple[float, float, float], color: str = GREY,
        collide: bool = True) -> str:
    sx, sy, sz = size
    geom = f"<geometry><box><size>{sx:.3f} {sy:.3f} {sz:.3f}</size></box></geometry>"
    collision = f"<collision name='collision'>{geom}</collision>" if collide else ""
    p = " ".join(f"{v:.4f}" for v in pose)
    return (
        f"    <model name='{name}'><static>true</static><pose>{p}</pose>"
        f"<link name='link'>{collision}<visual name='visual'>{geom}{_material(color)}</visual></link></model>\n"
    )


def sphere(name: str, xyz: tuple[float, float, float], radius: float, color: str = ROCK) -> str:
    geom = f"<geometry><sphere><radius>{radius:.3f}</radius></sphere></geometry>"
    x, y, z = xyz
    return (
        f"    <model name='{name}'><static>true</static><pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>"
        f"<link name='link'><collision name='collision'>{geom}</collision>"
        f"<visual name='visual'>{geom}{_material(color)}</visual></link></model>\n"
    )


def cylinder(name: str, xyz: tuple[float, float, float], radius: float, length: float, color: str = ORANGE) -> str:
    geom = f"<geometry><cylinder><radius>{radius:.3f}</radius><length>{length:.3f}</length></cylinder></geometry>"
    x, y, z = xyz
    return (
        f"    <model name='{name}'><static>true</static><pose>{x:.3f} {y:.3f} {z:.3f} 0 0 0</pose>"
        f"<link name='link'><collision name='collision'>{geom}</collision>"
        f"<visual name='visual'>{geom}{_material(color)}</visual></link></model>\n"
    )


def ramp(name: str, x0: float, y: float, angle_deg: float, length: float, width: float,
         thickness: float = 0.4, base_z: float = 0.0, descending: bool = False, color: str = CONCRETE) -> str:
    """Inclined slab starting at x0 (ground level base_z) rising along +x (or falling)."""
    theta = math.radians(angle_deg)
    cx = x0 + 0.5 * length * math.cos(theta)
    rise = 0.5 * length * math.sin(theta)
    cz = base_z + (rise if not descending else -rise) - 0.5 * thickness * math.cos(theta)
    if descending:
        cz += 2 * rise
    pitch = -theta if not descending else theta
    return box(name, (cx, y, cz, 0.0, pitch, 0.0), (length, width, thickness), color)


def wall(name: str, x1: float, y1: float, x2: float, y2: float, height: float = 2.5, thickness: float = 0.4,
         color: str = CONCRETE) -> str:
    length = math.hypot(x2 - x1, y2 - y1)
    yaw = math.atan2(y2 - y1, x2 - x1)
    return box(name, ((x1 + x2) / 2, (y1 + y2) / 2, height / 2, 0, 0, yaw), (length, thickness, height), color)


def boundary(prefix: str, xmin: float, ymin: float, xmax: float, ymax: float, height: float = 1.0) -> str:
    return (
        wall(f"{prefix}_s", xmin, ymin, xmax, ymin, height)
        + wall(f"{prefix}_n", xmin, ymax, xmax, ymax, height)
        + wall(f"{prefix}_w", xmin, ymin, xmin, ymax, height)
        + wall(f"{prefix}_e", xmax, ymin, xmax, ymax, height)
    )


def ditch(prefix: str, x0: float, y: float, width_y: float, platform_len: float, gap: float,
          height: float = 0.8) -> str:
    """Raised platform with a trench (negative obstacle) of ``gap`` metres, ramps at both ends."""
    out = ramp(f"{prefix}_ramp_up", x0, y, 8.0, height / math.sin(math.radians(8.0)), width_y)
    start = x0 + (height / math.tan(math.radians(8.0)))
    out += box(f"{prefix}_deck_a", (start + platform_len / 2, y, height / 2, 0, 0, 0), (platform_len, width_y, height), DIRT)
    b_start = start + platform_len + gap
    out += box(f"{prefix}_deck_b", (b_start + platform_len / 2, y, height / 2, 0, 0, 0), (platform_len, width_y, height), DIRT)
    out += ramp(f"{prefix}_ramp_down", b_start + platform_len, y, 8.0, height / math.sin(math.radians(8.0)),
                width_y, base_z=0.0, descending=True)
    return out


# --------------------------------------------------------------------- worlds
def world_flat() -> str:
    s = header("flat_test_track")
    # Oval track marked by cones; straightaways 80 m, turn radius 25 m.
    idx = 0
    for x in range(0, 81, 10):
        for y in (-29.0, -21.0, 21.0, 29.0):
            s += cylinder(f"cone_{idx}", (x, y, 0.4), 0.2, 0.8)
            idx += 1
    for side, cx in (("e", 80.0), ("w", 0.0)):
        for k in range(1, 8):
            a = math.pi * k / 8 - math.pi / 2
            sign = 1 if side == "e" else -1
            for r in (21.0, 29.0):
                s += cylinder(f"cone_{side}_{k}_{int(r)}", (cx + sign * r * math.cos(a), r * math.sin(a), 0.4), 0.2, 0.8)
    # Painted start line (visual only) and stopping-distance test box at the far end.
    s += box("start_line", (5.0, -25.0, 0.005, 0, 0, 0), (0.3, 8.0, 0.01), WHITE, collide=False)
    s += box("brake_test_marker", (60.0, -25.0, 0.005, 0, 0, 0), (0.3, 8.0, 0.01), WHITE, collide=False)
    s += boundary("fence", -60, -60, 140, 60)
    return s + FOOTER


def world_obstacle() -> str:
    s = header("obstacle_course")
    # Narrow corridor: 5.0 m clear width for a 3.4 m wide vehicle.
    s += wall("corridor_l", 20, 2.7, 50, 2.7)
    s += wall("corridor_r", 20, -2.7, 50, -2.7)
    # Dog-leg corridor
    s += wall("dogleg_a", 60, 3.5, 75, 3.5)
    s += wall("dogleg_b", 60, -3.5, 68, -3.5)
    s += wall("dogleg_c", 75, 3.5, 85, -6.5)
    s += wall("dogleg_d", 68, -3.5, 78, -13.5)
    # Positive obstacles: boxes and rocks
    rng = random.Random(2)
    for k in range(10):
        s += box(f"block_{k}", (rng.uniform(10, 90), rng.uniform(15, 40), 0.6, 0, 0, rng.uniform(0, 3.1)),
                 (rng.uniform(1.0, 2.5), rng.uniform(1.0, 2.5), 1.2))
    for k in range(14):
        r = rng.uniform(0.3, 1.0)
        s += sphere(f"rock_{k}", (rng.uniform(10, 90), rng.uniform(-40, -15), r * 0.6), r)
    # Ditch / negative obstacle and a ramp
    s += ditch("ditch", 95.0, 0.0, 8.0, 10.0, 1.8)
    s += ramp("ramp_a", 10.0, -50.0, 6.0, 12.0, 6.0)
    # Low wall (step obstacle) to test step height thresholds
    s += box("step_0p3", (100.0, -25.0, 0.15, 0, 0, 0), (1.0, 8.0, 0.3))
    s += box("step_0p8", (110.0, -25.0, 0.4, 0, 0, 0), (1.0, 8.0, 0.8))
    s += boundary("fence", -20, -60, 160, 60)
    return s + FOOTER


def world_rough() -> str:
    s = header("rough_terrain")
    rng = random.Random(3)
    # Uneven surface: many shallow tilted slabs and half-buried rocks over 100 x 60 m.
    for k in range(220):
        x, y = rng.uniform(5, 105), rng.uniform(-30, 30)
        h = rng.uniform(0.05, 0.25)
        s += box(f"slab_{k}", (x, y, h / 2 - 0.05, rng.uniform(-0.12, 0.12), rng.uniform(-0.12, 0.12), rng.uniform(0, 3.1)),
                 (rng.uniform(1.5, 4.0), rng.uniform(1.5, 4.0), h), DIRT)
    for k in range(60):
        r = rng.uniform(0.2, 0.9)
        s += sphere(f"rock_{k}", (rng.uniform(5, 105), rng.uniform(-30, 30), r * rng.uniform(-0.2, 0.5)), r)
    s += ditch("gully", 110.0, 0.0, 10.0, 8.0, 1.2, height=0.6)
    s += boundary("fence", -20, -50, 150, 50)
    return s + FOOTER


def world_slope() -> str:
    s = header("slope_course")
    # Four parallel up-plateau-down lanes at 5, 10, 15, 20 degrees.
    for lane, angle in enumerate((5.0, 10.0, 15.0, 20.0)):
        y = -27.0 + lane * 18.0
        height = 3.0
        theta = math.radians(angle)
        length = height / math.sin(theta)
        run = height / math.tan(theta)
        x0 = 10.0
        s += ramp(f"up_{int(angle)}", x0, y, angle, length, 7.0)
        s += box(f"plateau_{int(angle)}", (x0 + run + 7.5, y, height / 2, 0, 0, 0), (15.0, 7.0, height), CONCRETE)
        s += ramp(f"down_{int(angle)}", x0 + run + 15.0, y, angle, length, 7.0, descending=True)
    # Side-slope (roll) section: a slab tilted about x.
    s += box("side_slope_10", (40.0, 45.0, 0.9, math.radians(10.0), 0, 0), (40.0, 10.0, 0.4), DIRT)
    s += boundary("fence", -20, -50, 120, 60)
    return s + FOOTER


def world_gnss_degraded() -> str:
    s = header("gnss_degraded_course")
    # Built-up corridor: tall buildings either side (multipath / blockage) and an
    # overpass section with full sky occlusion. Degradation zones are listed in
    # the sidecar YAML for the failure-injection tooling.
    for k in range(6):
        x = 15.0 + k * 14.0
        s += box(f"bldg_n_{k}", (x, 14.0, 9.0, 0, 0, 0), (10.0, 12.0, 18.0), CONCRETE)
        s += box(f"bldg_s_{k}", (x, -14.0, 11.0, 0, 0, 0), (10.0, 12.0, 22.0), CONCRETE)
    # Overpass: deck on pillars, 6 m clearance.
    s += box("overpass_deck", (60.0, 0.0, 6.5, 0, 0, 0), (20.0, 16.0, 1.0), GREY)
    for px in (51.0, 69.0):
        for py in (-7.5, 7.5):
            s += box(f"pillar_{int(px)}_{int(py)}", (px, py, 3.0, 0, 0, 0), (1.0, 1.0, 6.0), GREY)
    # Parked obstacles in the corridor
    s += box("parked_a", (35.0, 4.0, 1.25, 0, 0, 0), (6.0, 2.5, 2.5), WHITE)
    s += box("parked_b", (90.0, -4.0, 1.25, 0, 0, 0), (6.0, 2.5, 2.5), WHITE)
    s += boundary("fence", -20, -40, 130, 40)
    return s + FOOTER


WORLDS = {
    "01_flat_test_track": world_flat,
    "02_obstacle_course": world_obstacle,
    "03_rough_terrain": world_rough,
    "04_slope_course": world_slope,
    "05_gnss_degraded_course": world_gnss_degraded,
}

GNSS_ZONES = {
    "zones": [
        {"name": "urban_canyon", "polygon": [8, -8, 92, -8, 92, 8, 8, 8], "effect": "degraded",
         "position_stddev": 2.5},
        {"name": "overpass", "polygon": [50, -8, 70, -8, 70, 8, 50, 8], "effect": "denied"},
    ]
}


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.mkdir(parents=True, exist_ok=True)
    for name, builder in WORLDS.items():
        (out / f"{name}.sdf").write_text(builder(), encoding="utf-8")
    (out / "05_gnss_degraded_course.zones.yaml").write_text(
        "# GNSS degradation zones (odom/world frame, metres) used by failure injection.\n"
        + yaml.safe_dump(GNSS_ZONES, sort_keys=False),
        encoding="utf-8",
    )
    print(f"wrote {len(WORLDS)} worlds to {out}")


if __name__ == "__main__":
    main()
